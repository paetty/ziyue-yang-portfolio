function applyZoom() {
  if (fitMode) {
    lightboxImage.style.width = "auto";
    lightboxImage.style.height = "auto";
    lightboxImage.style.maxWidth = "calc(96vw - 34px)";
    lightboxImage.style.maxHeight = "calc(94vh - 116px)";
    zoomValue.textContent = activeLanguage === "zh" ? "适应" : "Fit";
  } else {
    lightboxImage.style.maxWidth = "none";
    lightboxImage.style.maxHeight = "none";
    lightboxImage.style.width = `${lightboxImage.naturalWidth * zoom}px`;
    lightboxImage.style.height = "auto";
    zoomValue.textContent = `${Math.round(zoom * 100)}%`;
  }
}

function openLightbox(source, alt, caption = "") {
  lightboxImage.src = source;
  lightboxImage.alt = alt || "";
  lightboxCaption.textContent = caption;
  zoom = 1;
  fitMode = true;
  lightbox.showModal();
  lightboxImage.addEventListener("load", applyZoom, { once: true });
}

function bindExpandableImage(image) {
  image.tabIndex = 0;
  image.setAttribute("role", "button");
  image.setAttribute("aria-label", `Expand image: ${image.alt}`);
  const open = () => openLightbox(image.currentSrc || image.src, image.alt);
  image.addEventListener("click", open);
  image.addEventListener("keydown", (event) => { if (event.key === "Enter" || event.key === " ") open(); });
}

function bindHorizontalSwipe(element, onSwipeLeft, onSwipeRight) {
  let startX = 0;
  let startY = 0;
  element.addEventListener("touchstart", (event) => {
    startX = event.changedTouches[0].clientX;
    startY = event.changedTouches[0].clientY;
  }, { passive: true });
  element.addEventListener("touchend", (event) => {
    const deltaX = event.changedTouches[0].clientX - startX;
    const deltaY = event.changedTouches[0].clientY - startY;
    if (Math.abs(deltaX) < 48 || Math.abs(deltaX) < Math.abs(deltaY)) return;
    if (deltaX < 0) onSwipeLeft();
    else onSwipeRight();
  }, { passive: true });
}

function createCarouselDots(container, count, goTo, labelPrefix) {
  return Array.from({ length: count }, (_, index) => {
    const dot = document.createElement("button");
    dot.type = "button";
    dot.setAttribute("aria-label", `${labelPrefix} ${index + 1}`);
    dot.addEventListener("click", () => goTo(index));
    container.append(dot);
    return dot;
  });
}

function initializeProjectCarousel() {
  if (!projectCarousel || !projectSlides.length) return null;
  const previous = projectCarousel.querySelector("[data-project-prev]");
  const next = projectCarousel.querySelector("[data-project-next]");
  const dotsContainer = projectCarousel.querySelector("[data-project-dots]");
  let index = 0;
  let dots = [];
  const goTo = (target) => {
    index = (target + projectSlides.length) % projectSlides.length;
    projectSlides.forEach((slide, slideIndex) => {
      const active = slideIndex === index;
      slide.classList.toggle("is-active", active);
      slide.setAttribute("aria-hidden", String(!active));
      slide.querySelectorAll("button, a").forEach((control) => { control.tabIndex = active ? 0 : -1; });
    });
    dots.forEach((dot, dotIndex) => {
      dot.classList.toggle("is-active", dotIndex === index);
      dot.setAttribute("aria-current", dotIndex === index ? "true" : "false");
    });
  };
  dots = createCarouselDots(dotsContainer, projectSlides.length, goTo, "Project");
  const showNext = () => goTo(index + 1);
  const showPrevious = () => goTo(index - 1);
  previous.addEventListener("click", showPrevious);
  next.addEventListener("click", showNext);
  projectCarousel.addEventListener("keydown", (event) => {
    if (event.key === "ArrowLeft") showPrevious();
    if (event.key === "ArrowRight") showNext();
  });
  bindHorizontalSwipe(projectCarousel, showNext, showPrevious);
  goTo(0);
  return { goTo, sync: () => goTo(index) };
}

function initializeDetailGallery(gallery) {
  const slides = [...gallery.querySelectorAll(":scope > button")];
  if (!slides.length) return null;
  const shell = document.createElement("div");
  shell.className = "detail-gallery-shell";
  const previous = document.createElement("button");
  previous.type = "button";
  previous.className = "gallery-nav";
  previous.setAttribute("aria-label", "Previous image");
  previous.textContent = "←";
  const next = document.createElement("button");
  next.type = "button";
  next.className = "gallery-nav";
  next.setAttribute("aria-label", "Next image");
  next.textContent = "→";
  gallery.before(shell);
  shell.append(previous, gallery, next);

  const status = document.createElement("div");
  status.className = "detail-gallery-status";
  const counter = document.createElement("span");
  const caption = document.createElement("p");
  const dotsContainer = document.createElement("div");
  dotsContainer.className = "gallery-dots";
  status.append(counter, caption, dotsContainer);
  shell.after(status);

  let index = 0;
  let dots = [];
  const sync = () => {
    slides.forEach((slide, slideIndex) => {
      const active = slideIndex === index;
      slide.classList.toggle("is-active", active);
      slide.setAttribute("aria-hidden", String(!active));
      slide.tabIndex = active ? 0 : -1;
    });
    dots.forEach((dot, dotIndex) => {
      dot.classList.toggle("is-active", dotIndex === index);
      dot.setAttribute("aria-current", dotIndex === index ? "true" : "false");
    });
    counter.textContent = `${String(index + 1).padStart(2, "0")} / ${String(slides.length).padStart(2, "0")}`;
    caption.textContent = slides[index].querySelector("span")?.textContent || "";
  };
  const goTo = (target) => {
    index = (target + slides.length) % slides.length;
    sync();
  };
  dots = createCarouselDots(dotsContainer, slides.length, goTo, "Image");
  previous.addEventListener("click", () => goTo(index - 1));
  next.addEventListener("click", () => goTo(index + 1));
  shell.tabIndex = 0;
  shell.addEventListener("keydown", (event) => {
    if (event.key === "ArrowLeft") goTo(index - 1);
    if (event.key === "ArrowRight") goTo(index + 1);
  });
  bindHorizontalSwipe(shell, () => goTo(index + 1), () => goTo(index - 1));
  goTo(0);
  return { goTo, sync };
}

function initializeCampusGallery(gallery) {
  const slides = [...gallery.querySelectorAll(".campus-photo-stage figure")];
  const previous = gallery.querySelector("[data-campus-prev]");
  const next = gallery.querySelector("[data-campus-next]");
  const dotsContainer = gallery.querySelector("[data-campus-dots]");
  if (!slides.length || !previous || !next || !dotsContainer) return null;
  let index = 0;
  let dots = [];
  const goTo = (target) => {
    index = (target + slides.length) % slides.length;
    const previousIndex = (index - 1 + slides.length) % slides.length;
    const nextIndex = (index + 1) % slides.length;
    slides.forEach((slide, slideIndex) => {
      const active = slideIndex === index;
      const before = slideIndex === previousIndex;
      const after = slideIndex === nextIndex;
      slide.classList.toggle("is-active", active);
      slide.classList.toggle("is-side-before", before);
      slide.classList.toggle("is-side-after", after);
      slide.setAttribute("aria-hidden", String(!(active || before || after)));
    });
    dots.forEach((dot, dotIndex) => {
      dot.classList.toggle("is-active", dotIndex === index);
      dot.setAttribute("aria-current", dotIndex === index ? "true" : "false");
    });
  };
  dots = createCarouselDots(dotsContainer, slides.length, goTo, "Campus photo");
  previous.addEventListener("click", () => goTo(index - 1));
  next.addEventListener("click", () => goTo(index + 1));
  gallery.tabIndex = 0;
  gallery.addEventListener("keydown", (event) => {
    if (event.key === "ArrowLeft") goTo(index - 1);
    if (event.key === "ArrowRight") goTo(index + 1);
  });
  bindHorizontalSwipe(gallery, () => goTo(index + 1), () => goTo(index - 1));
  goTo(0);
  return { goTo };
}

