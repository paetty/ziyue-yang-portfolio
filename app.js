function resetScrollIntent() {
  window.clearTimeout(scrollIntentTimer);
  scrollGestureCount = 0;
  lastScrollDirection = 0;
  lastScrollGestureAt = 0;
  scrollFeedback.classList.remove("is-visible", "is-committing");
}

function getScrollTarget(direction) {
  const currentView = document.querySelector(".view.is-active")?.dataset.view || "overview";
  const currentIndex = viewOrder.indexOf(currentView);
  if (currentIndex < 0) return null;
  const targetIndex = currentIndex + direction;
  return targetIndex >= 0 && targetIndex < viewOrder.length ? viewOrder[targetIndex] : null;
}

function showScrollFeedback(direction, committing = false) {
  const key = committing
    ? (direction > 0 ? "scrollMovingDown" : "scrollMovingUp")
    : (direction > 0 ? "scrollAgainDown" : "scrollAgainUp");
  scrollFeedbackText.textContent = translations[activeLanguage][key];
  scrollFeedbackArrow.textContent = direction > 0 ? "↓" : "↑";
  scrollFeedback.classList.add("is-visible");
  scrollFeedback.classList.toggle("is-committing", committing);
}

function registerBoundaryGesture(direction) {
  if (scrollTransitionLocked || !getScrollTarget(direction)) return;
  const now = Date.now();
  const continues = direction === lastScrollDirection && now - lastScrollGestureAt < 4200;
  scrollGestureCount = continues ? scrollGestureCount + 1 : 1;
  lastScrollDirection = direction;
  lastScrollGestureAt = now;
  window.clearTimeout(scrollIntentTimer);

  if (scrollGestureCount < 2) {
    showScrollFeedback(direction, false);
    scrollIntentTimer = window.setTimeout(resetScrollIntent, 4200);
    return;
  }

  const target = getScrollTarget(direction);
  showScrollFeedback(direction, true);
  scrollTransitionLocked = true;
  scrollIntentTimer = window.setTimeout(() => {
    showView(target);
    window.setTimeout(() => { scrollTransitionLocked = false; }, 650);
  }, 240);
}

function isAtBoundary(direction) {
  if (direction > 0) return window.scrollY + window.innerHeight >= document.documentElement.scrollHeight - 6;
  return window.scrollY <= 6;
}

window.addEventListener("wheel", (event) => {
  if (scrollTransitionLocked || projectDialog.open || contactDialog.open || lightbox.open) return;
  const direction = Math.sign(event.deltaY);
  if (!direction) return;
  if (!isAtBoundary(direction)) {
    wheelBurst = 0;
    window.clearTimeout(wheelBurstTimer);
    resetScrollIntent();
    return;
  }
  wheelBurst += event.deltaY;
  window.clearTimeout(wheelBurstTimer);
  wheelBurstTimer = window.setTimeout(() => {
    const burstDirection = Math.sign(wheelBurst);
    if (Math.abs(wheelBurst) >= 28) registerBoundaryGesture(burstDirection);
    wheelBurst = 0;
  }, 130);
}, { passive: true });

let touchStartY = 0;
document.addEventListener("touchstart", (event) => {
  touchStartY = event.changedTouches[0]?.clientY || 0;
}, { passive: true });
document.addEventListener("touchend", (event) => {
  if (projectDialog.open || contactDialog.open || lightbox.open) return;
  const endY = event.changedTouches[0]?.clientY || touchStartY;
  const delta = touchStartY - endY;
  if (Math.abs(delta) < 58) return;
  const direction = Math.sign(delta);
  if (isAtBoundary(direction)) registerBoundaryGesture(direction);
}, { passive: true });

